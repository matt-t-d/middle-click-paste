//! System (general) pasteboard access via the Objective-C runtime.
//!
//! Everything here is hand-written FFI: `objc_msgSend` is transmuted to the
//! exact function-pointer type of each message (arm64, so no `_stret`).
//! Every public function runs inside its own autorelease pool, so it is safe
//! to call from threads that have none.

use crate::ffi;
use std::ffi::c_void;
use std::mem::transmute;
use std::os::raw::c_char;

type Id = *mut c_void;
type Sel = *const c_void;

#[link(name = "objc")]
extern "C" {
    fn objc_getClass(name: *const c_char) -> Id;
    fn sel_registerName(name: *const c_char) -> Sel;
    fn objc_msgSend();
    fn objc_autoreleasePoolPush() -> *mut c_void;
    fn objc_autoreleasePoolPop(pool: *mut c_void);
}

// Linked only so the classes (NSPasteboard, NSPasteboardItem, NSData, ...) are loaded.
#[link(name = "AppKit", kind = "framework")]
extern "C" {}
#[link(name = "Foundation", kind = "framework")]
extern "C" {}

const NS_UTF8_STRING_ENCODING: usize = 4;
const TYPE_STRING: &str = "public.utf8-plain-text";
const TYPE_TRANSIENT: &str = "org.nspasteboard.TransientType";
const TYPE_AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";

/// Full copy of the general pasteboard's contents (every item, every type).
#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct Snapshot {
    /// One entry per `NSPasteboardItem`, in pasteboard order; each holds
    /// `(type UTI, raw data)` pairs in the item's own type order.
    items: Vec<Vec<(String, Vec<u8>)>>,
}

// ---------------------------------------------------------------------------
// Runtime helpers
// ---------------------------------------------------------------------------

/// Autorelease pool that is popped on drop (including during unwinding).
struct Pool(*mut c_void);

impl Pool {
    fn new() -> Pool {
        Pool(unsafe { objc_autoreleasePoolPush() })
    }
}

impl Drop for Pool {
    fn drop(&mut self) {
        unsafe { objc_autoreleasePoolPop(self.0) }
    }
}

/// `name` must be NUL-terminated.
unsafe fn class(name: &'static str) -> Id {
    debug_assert!(name.ends_with('\0'));
    objc_getClass(name.as_ptr() as *const c_char)
}

/// `name` must be NUL-terminated.
unsafe fn sel(name: &'static str) -> Sel {
    debug_assert!(name.ends_with('\0'));
    sel_registerName(name.as_ptr() as *const c_char)
}

unsafe fn msg_id(obj: Id, s: Sel) -> Id {
    let f: unsafe extern "C" fn(Id, Sel) -> Id = transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s)
}

unsafe fn msg_id_id(obj: Id, s: Sel, a: Id) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, Id) -> Id =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s, a)
}

unsafe fn msg_isize(obj: Id, s: Sel) -> isize {
    let f: unsafe extern "C" fn(Id, Sel) -> isize =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s)
}

unsafe fn msg_usize(obj: Id, s: Sel) -> usize {
    let f: unsafe extern "C" fn(Id, Sel) -> usize =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s)
}

unsafe fn msg_id_usize(obj: Id, s: Sel, a: usize) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, usize) -> Id =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s, a)
}

unsafe fn msg_bool_id(obj: Id, s: Sel, a: Id) -> bool {
    let f: unsafe extern "C" fn(Id, Sel, Id) -> bool =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s, a)
}

unsafe fn msg_bool_id_id(obj: Id, s: Sel, a: Id, b: Id) -> bool {
    let f: unsafe extern "C" fn(Id, Sel, Id, Id) -> bool =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(obj, s, a, b)
}

unsafe fn general_pasteboard() -> Id {
    msg_id(class("NSPasteboard\0"), sel("generalPasteboard\0"))
}

/// Owned NSString (toll-free bridged CFString), released on drop.
struct NsString(ffi::CFStringRef);

impl NsString {
    fn new(s: &str) -> NsString {
        NsString(ffi::cfstring(s))
    }
    fn id(&self) -> Id {
        self.0 as Id
    }
}

impl Drop for NsString {
    fn drop(&mut self) {
        if !self.0.is_null() {
            unsafe { ffi::CFRelease(self.0) }
        }
    }
}

/// Autoreleased NSData holding a copy of `bytes`.
unsafe fn nsdata(bytes: &[u8]) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, *const u8, usize) -> Id =
        transmute(objc_msgSend as unsafe extern "C" fn());
    f(
        class("NSData\0"),
        sel("dataWithBytes:length:\0"),
        bytes.as_ptr(),
        bytes.len(),
    )
}

unsafe fn nsdata_to_vec(data: Id) -> Vec<u8> {
    let len = msg_usize(data, sel("length\0"));
    if len == 0 {
        return Vec::new();
    }
    let ptr = msg_id(data, sel("bytes\0")) as *const u8;
    if ptr.is_null() {
        return Vec::new();
    }
    std::slice::from_raw_parts(ptr, len).to_vec()
}

/// NSString -> String via an explicit-length UTF-8 NSData (safe for interior
/// NULs; unpaired surrogates are converted lossily rather than failing).
unsafe fn nsstring_to_string(s: Id) -> Option<String> {
    if s.is_null() {
        return None;
    }
    let f: unsafe extern "C" fn(Id, Sel, usize, bool) -> Id =
        transmute(objc_msgSend as unsafe extern "C" fn());
    let data = f(
        s,
        sel("dataUsingEncoding:allowLossyConversion:\0"),
        NS_UTF8_STRING_ENCODING,
        true,
    );
    if data.is_null() {
        return None;
    }
    Some(String::from_utf8_lossy(&nsdata_to_vec(data)).into_owned())
}

/// Clear the pasteboard and write `items` (one NSPasteboardItem each).
unsafe fn write_items(items: &[Vec<(String, Vec<u8>)>]) {
    let pb = general_pasteboard();
    if pb.is_null() {
        return;
    }
    msg_isize(pb, sel("clearContents\0"));

    let array = msg_id(class("NSMutableArray\0"), sel("array\0"));
    let mut count = 0usize;
    for item in items {
        if item.is_empty() {
            continue;
        }
        let obj = msg_id(
            msg_id(class("NSPasteboardItem\0"), sel("alloc\0")),
            sel("init\0"),
        );
        if obj.is_null() {
            continue;
        }
        let mut wrote = false;
        for (ty, bytes) in item {
            let ty = NsString::new(ty);
            if ty.id().is_null() {
                continue;
            }
            wrote |= msg_bool_id_id(obj, sel("setData:forType:\0"), nsdata(bytes), ty.id());
        }
        if wrote {
            let add: unsafe extern "C" fn(Id, Sel, Id) =
                transmute(objc_msgSend as unsafe extern "C" fn());
            add(array, sel("addObject:\0"), obj);
            count += 1;
        }
        // The array (if it took it) keeps the item alive; drop our +1.
        let release: unsafe extern "C" fn(Id, Sel) =
            transmute(objc_msgSend as unsafe extern "C" fn());
        release(obj, sel("release\0"));
    }
    if count > 0 {
        msg_bool_id(pb, sel("writeObjects:\0"), array);
    }
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/// `NSPasteboard.general.changeCount`.
pub fn change_count() -> i64 {
    let _pool = Pool::new();
    unsafe {
        let pb = general_pasteboard();
        if pb.is_null() {
            return 0;
        }
        msg_isize(pb, sel("changeCount\0")) as i64
    }
}

/// Plain-text contents of the general pasteboard, if any. When the pasteboard
/// holds several items, AppKit joins each item's string with `"\n"`.
pub fn read_string() -> Option<String> {
    let _pool = Pool::new();
    unsafe {
        let pb = general_pasteboard();
        if pb.is_null() {
            return None;
        }
        let ty = NsString::new(TYPE_STRING);
        nsstring_to_string(msg_id_id(pb, sel("stringForType:\0"), ty.id()))
    }
}

/// Capture everything currently on the general pasteboard.
pub fn snapshot() -> Snapshot {
    let _pool = Pool::new();
    let mut snap = Snapshot::default();
    unsafe {
        let pb = general_pasteboard();
        if pb.is_null() {
            return snap;
        }
        let items = msg_id(pb, sel("pasteboardItems\0"));
        if items.is_null() {
            return snap;
        }
        let n_items = msg_usize(items, sel("count\0"));
        for i in 0..n_items {
            // Inner pool: item data can be large (images), free it per item.
            let _inner = Pool::new();
            let item = msg_id_usize(items, sel("objectAtIndex:\0"), i);
            let types = msg_id(item, sel("types\0"));
            let mut entry = Vec::new();
            if !types.is_null() {
                let n_types = msg_usize(types, sel("count\0"));
                for j in 0..n_types {
                    let ty = msg_id_usize(types, sel("objectAtIndex:\0"), j);
                    let data = msg_id_id(item, sel("dataForType:\0"), ty);
                    if data.is_null() {
                        // Declared but not deliverable (e.g. a promise whose
                        // owner is gone); nothing we could write back.
                        continue;
                    }
                    if let Some(name) = nsstring_to_string(ty) {
                        entry.push((name, nsdata_to_vec(data)));
                    }
                }
            }
            snap.items.push(entry);
        }
    }
    snap
}

/// Put a snapshot back, replacing whatever is there now.
pub fn restore(snap: &Snapshot) {
    let _pool = Pool::new();
    unsafe { write_items(&snap.items) }
}

/// Replace the pasteboard with `text`, flagged as transient/auto-generated
/// (nspasteboard.org conventions) so clipboard managers ignore it.
pub fn write_transient_string(text: &str) {
    let _pool = Pool::new();
    let item = vec![
        (TYPE_STRING.to_string(), text.as_bytes().to_vec()),
        (TYPE_TRANSIENT.to_string(), Vec::new()),
        (TYPE_AUTO_GENERATED.to_string(), Vec::new()),
    ];
    unsafe { write_items(&[item]) }
}

// ---------------------------------------------------------------------------
// Tests (touch the real general pasteboard; run with --test-threads=1)
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;

    /// Snapshots the user's clipboard now and restores it on drop (even on panic).
    struct Guard(Snapshot);

    impl Guard {
        fn new() -> Guard {
            Guard(snapshot())
        }
    }

    impl Drop for Guard {
        fn drop(&mut self) {
            restore(&self.0);
        }
    }

    fn types_of(snap: &Snapshot, item: usize) -> Vec<&str> {
        snap.items[item].iter().map(|(t, _)| t.as_str()).collect()
    }

    fn data_of<'a>(snap: &'a Snapshot, item: usize, ty: &str) -> Option<&'a [u8]> {
        snap.items[item]
            .iter()
            .find(|(t, _)| t == ty)
            .map(|(_, d)| d.as_slice())
    }

    /// Independent reader: the system `pbpaste` tool.
    fn pbpaste() -> Vec<u8> {
        std::process::Command::new("/usr/bin/pbpaste")
            .env("LC_ALL", "en_US.UTF-8")
            .output()
            .expect("run pbpaste")
            .stdout
    }

    #[test]
    fn transient_string_round_trip() {
        let _g = Guard::new();
        for text in [
            "plain ascii",
            "h\u{e9}llo w\u{f6}rld \u{65e5}\u{672c}\u{8a9e} \u{1f600}\u{1f468}\u{200d}\u{1f469}\u{200d}\u{1f467} e\u{301}",
            "line1\nline2\ttab\r\n",
            "interior\0nul\0bytes",
            "",
        ] {
            write_transient_string(text);
            assert_eq!(read_string().as_deref(), Some(text), "text {:?}", text);
        }

        // Cross-check with an independent reader.
        let text = "caf\u{e9} \u{1f600} \u{4e2d}\u{6587}";
        write_transient_string(text);
        assert_eq!(pbpaste(), text.as_bytes());

        // Marker types are present, with empty data, alongside the string.
        let snap = snapshot();
        assert_eq!(snap.items.len(), 1);
        assert_eq!(data_of(&snap, 0, TYPE_STRING), Some(text.as_bytes()));
        assert_eq!(data_of(&snap, 0, TYPE_TRANSIENT), Some(&[][..]));
        assert_eq!(data_of(&snap, 0, TYPE_AUTO_GENERATED), Some(&[][..]));
    }

    #[test]
    fn change_count_increases() {
        let _g = Guard::new();
        let a = change_count();
        write_transient_string("one");
        let b = change_count();
        assert!(b > a, "{} !> {}", b, a);
        assert_eq!(change_count(), b, "stable without writes");
        write_transient_string("two");
        let c = change_count();
        assert!(c > b, "{} !> {}", c, b);
        restore(&snapshot());
        assert!(change_count() > c);
    }

    #[test]
    fn snapshot_restore_multi_type_multi_item() {
        let _g = Guard::new();
        let custom = "com.example.middle-click-paste.test-blob";
        let blob: Vec<u8> = (0..=255u8).chain([0, 0, 255, 0]).collect();
        let original = Snapshot {
            items: vec![
                vec![
                    (TYPE_STRING.to_string(), "first \u{1f980} item".as_bytes().to_vec()),
                    (custom.to_string(), blob.clone()),
                    ("public.html".to_string(), b"<b>first</b>".to_vec()),
                ],
                vec![
                    (TYPE_STRING.to_string(), b"second item".to_vec()),
                    (custom.to_string(), vec![0xde, 0xad, 0xbe, 0xef]),
                ],
            ],
        };
        restore(&original);

        let snap = snapshot();
        assert_eq!(snap.items.len(), 2);
        assert_eq!(types_of(&snap, 0), [TYPE_STRING, custom, "public.html"]);
        assert_eq!(data_of(&snap, 0, custom), Some(blob.as_slice()));
        assert_eq!(snap, original);

        // Overwrite (what the app does while pasting) ...
        write_transient_string("our transient text");
        assert_eq!(read_string().as_deref(), Some("our transient text"));
        let during = snapshot();
        assert_eq!(during.items.len(), 1);
        assert_eq!(data_of(&during, 0, custom), None);

        // ... and bring the user's content back.
        restore(&snap);
        let after = snapshot();
        assert_eq!(after, original);
        assert_eq!(data_of(&after, 0, custom), Some(blob.as_slice()));
        assert_eq!(data_of(&after, 1, custom), Some(&[0xde, 0xad, 0xbe, 0xef][..]));
        // With several items, AppKit's stringForType: joins every item's
        // string with "\n" (same as what a plain Cmd+V would paste).
        assert_eq!(
            read_string().as_deref(),
            Some("first \u{1f980} item\nsecond item")
        );
    }

    #[test]
    fn empty_snapshot_restores_to_empty() {
        let _g = Guard::new();
        write_transient_string("something");
        let before = change_count();
        restore(&Snapshot::default());
        assert!(change_count() > before);
        assert_eq!(read_string(), None);
        assert!(snapshot().items.is_empty());
    }

    #[test]
    fn works_from_background_thread() {
        let _g = Guard::new();
        std::thread::spawn(|| {
            write_transient_string("from thread \u{1f9f5}");
            let snap = snapshot();
            assert_eq!(read_string().as_deref(), Some("from thread \u{1f9f5}"));
            write_transient_string("other");
            restore(&snap);
            assert_eq!(read_string().as_deref(), Some("from thread \u{1f9f5}"));
            assert!(change_count() > 0);
        })
        .join()
        .unwrap();
    }
}
